CREATE TABLE IF NOT EXISTS elite_drivers (
 id INTEGER PRIMARY KEY CHECK(id BETWEEN 1 AND 10000),
 n TEXT NOT NULL COLLATE NOCASE UNIQUE CHECK(length(n) BETWEEN 1 AND 60),
 state TEXT NOT NULL, club TEXT NOT NULL, photo TEXT NOT NULL DEFAULT '',
 q INTEGER, s INTEGER, p INTEGER, f INTEGER,
 recorded TEXT NOT NULL DEFAULT '{}', is_dummy INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS admin_login_attempts (
 key TEXT PRIMARY KEY, attempts INTEGER NOT NULL, reset_at INTEGER NOT NULL
);
